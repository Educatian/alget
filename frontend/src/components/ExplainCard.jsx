import { useEffect, useState } from 'react'
import { Sparkles, X } from 'lucide-react'
import { explainPassage } from '../lib/tutorClient'

const MODES = [
    { id: 'explain', label: 'Explain' },
    { id: 'simpler', label: 'Simpler' },
    { id: 'example', label: 'Example' },
    { id: 'quiz_me', label: 'Quiz me' },
]

/**
 * AI explanation of a selected passage, grounded only in its section (see the tutor worker).
 * Clearly labelled as AI; the reader may save it as a note on the passage.
 */
export default function ExplainCard({ request, sectionId, onClose, onSaveNote, onLog }) {
    const [mode, setMode] = useState('explain')
    const [state, setState] = useState({ loading: true })

    useEffect(() => {
        let cancelled = false
        setState({ loading: true })
        explainPassage({ sectionId, exact: request.quote, mode }).then((res) => {
            if (cancelled) return
            setState(res?.explanation ? { result: res } : { error: res?.error || 'unavailable' })
            onLog?.(mode, res?.explanation ? 'ok' : String(res?.error || 'unavailable'))
        })
        return () => { cancelled = true }
        // onLog is a logging callback; re-requesting when it changes identity would double-charge.
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [request.quote, sectionId, mode])

    useEffect(() => {
        const onKey = (e) => { if (e.key === 'Escape') onClose() }
        window.addEventListener('keydown', onKey)
        return () => window.removeEventListener('keydown', onKey)
    }, [onClose])

    const { result } = state
    return (
        <aside role="dialog" aria-label="AI explanation" className="fixed bottom-4 right-4 z-[130] flex max-h-[70vh] w-[min(26rem,calc(100vw-2rem))] flex-col rounded-2xl border border-[var(--ath-line)] bg-[var(--ath-panel)] text-[var(--ath-text)] shadow-[var(--ath-shadow)]">
            <header className="flex items-center gap-2 border-b border-[var(--ath-line)] px-4 py-3">
                <Sparkles className="h-4 w-4 text-[var(--ath-primary)]" aria-hidden="true" />
                <h2 className="mr-auto text-sm font-semibold">AI explanation</h2>
                <button type="button" onClick={onClose} aria-label="Close explanation" className="flex h-9 w-9 items-center justify-center rounded-lg hover:bg-[var(--ath-panel-muted)]">
                    <X className="h-4 w-4" aria-hidden="true" />
                </button>
            </header>
            <div className="overflow-y-auto px-4 py-3">
                <p className="line-clamp-3 border-l-2 border-[var(--ath-line-strong)] pl-3 text-xs italic leading-5 text-[var(--ath-muted)]">“{request.quote}”</p>
                <div className="mt-3 flex gap-1 rounded-xl bg-[var(--ath-panel-muted)] p-1" role="tablist" aria-label="Kind of help">
                    {MODES.map((m) => (
                        <button key={m.id} type="button" role="tab" aria-selected={mode === m.id} onClick={() => setMode(m.id)}
                            className={`min-h-[34px] flex-1 rounded-lg px-2 text-xs font-semibold ${mode === m.id ? 'bg-[var(--ath-panel)] text-[var(--ath-text)] shadow-sm' : 'text-[var(--ath-muted)] hover:text-[var(--ath-text)]'}`}>
                            {m.label}
                        </button>
                    ))}
                </div>
                <div className="mt-3 min-h-[5rem] text-sm leading-6" aria-live="polite">
                    {state.loading && <p className="animate-pulse text-[var(--ath-muted)]">Thinking…</p>}
                    {state.error && <p className="text-[var(--ath-muted)]">The AI explanation isn&apos;t available right now. Try the read-aloud or reread the paragraph around it.</p>}
                    {result && (
                        <>
                            <p>{result.explanation}</p>
                            {result.check_question && <p className="mt-3 rounded-lg bg-[var(--ath-panel-muted)] px-3 py-2"><span className="font-semibold">Check yourself:</span> {result.check_question}</p>}
                            {!result.in_section && <p className="mt-2 text-xs text-[var(--ath-muted)]">This section doesn&apos;t fully cover that, so the answer is limited.</p>}
                        </>
                    )}
                </div>
            </div>
            <footer className="flex items-center gap-2 border-t border-[var(--ath-line)] px-4 py-2">
                <p className="mr-auto text-[11px] leading-4 text-[var(--ath-muted)]">Generated by AI from this section only. It can be wrong.</p>
                {result && (
                    <button type="button" onClick={() => onSaveNote(`AI explanation (${MODES.find((m) => m.id === mode).label}): ${result.explanation}`)}
                        className="min-h-[36px] rounded-lg px-3 text-xs font-semibold text-[var(--ath-primary)] hover:bg-[var(--ath-panel-muted)]">
                        Save as note
                    </button>
                )}
            </footer>
        </aside>
    )
}
